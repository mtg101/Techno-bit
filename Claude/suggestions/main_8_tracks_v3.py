def on_forever():
    global playing_song, current_song_position, start_track, choosing_song, is_playing
    if input.button_is_pressed(Button.B):
        if not (is_playing):
            if choosing_song:
                playing_song = True
                current_song_position = 0
                if current_track == 0:
                    radio.send_string("start song")
                start_track = True
            else:
                choosing_song = True
                show_song_name()
        else:
            if current_track == 0:
                radio.send_string("stop")
            playing_song = False
            is_playing = False
            choosing_song = False
        while input.button_is_pressed(Button.B):
            basic.pause(50)
basic.forever(on_forever)

def on_forever2():
    global current_pattern, current_song_position, new_pattern, start_track, choosing_song
    if start_track:
        if playing_song:
            new_pattern = False
            while current_song_position < len(song_list[current_song]) and playing_song:
                if current_track == 0:
                    radio.send_string(convert_to_text(song_list[current_song][current_song_position]))
                    if current_song_position == len(song_list[current_song]) - 1:
                        radio.send_string("end song")
                current_pattern = song_list[current_song][current_song_position]
                play_current_pattern()
                current_song_position += 1
        else:
            new_pattern = True
            while new_pattern:
                new_pattern = False
                play_current_pattern()
                while receiving_song and not (new_pattern):
                    basic.pause(1)
        start_track = False
        choosing_song = False
        if not (receiving_song):
            show_track_name()
basic.forever(on_forever2)
