def on_forever():
    global receiving_song, playing_song, current_song_position, start_track, is_playing
    if input.button_is_pressed(Button.B):
        if receiving_song:
            receiving_song = False
            is_playing = False
        elif not (is_playing):
            playing_song = True
            current_song_position = 0
            start_track = True
        else:
            if current_track == 0:
                radio.send_string("stop")
            playing_song = False
            is_playing = False
        while input.button_is_pressed(Button.B):
            basic.pause(50)
basic.forever(on_forever)

def on_forever2():
    global new_pattern, current_pattern, current_song_position, start_track
    if start_track:
        if playing_song:
            new_pattern = False
            while current_song_position < len(song) and playing_song:
                if current_track == 0:
                    radio.send_string(convert_to_text(song[current_song_position]))
                    if current_song_position == len(song) - 1:
                        radio.send_string("end song")
                current_pattern = song[current_song_position]
                play_current_pattern()
                current_song_position += 1
        else:
            new_pattern = True
            while new_pattern:
                new_pattern = False
                play_current_pattern()
                if receiving_song and not (new_pattern):
                    show_waiting()
                while receiving_song and not (new_pattern):
                    basic.pause(1)
        start_track = False
        if not (receiving_song):
            show_track_name()
basic.forever(on_forever2)
